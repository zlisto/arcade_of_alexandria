"""Regenerate World 0's overworld map in game_concept.json from src/world/retractReef.json,
so the bible's map, the playable overworld and the intro all show the same world.

Usage (from games/algebraic_topology):  python scripts/sync_map.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
layout = json.loads((ROOT / "src/world/retractReef.json").read_text(encoding="utf-8"))


def to_map(x, z):
    """World → map units (100 × 60). Keep in sync with worldToMap in src/world/reef.js."""
    s = 1.395
    return [round(50 + (x - 0.5) * s, 1), round(30 + (z + 8.5) * s, 1)]


sites, paths = [], []
for s in layout["sites"]:
    x, y = to_map(*s["pos"])
    site = {"id": s["id"], "name": s["name"], "kind": s["kind"], "x": x, "y": y}
    if s.get("level_id"):
        site["level_id"] = s["level_id"]
    if s.get("stage"):
        site["stage"] = s["stage"]
    if s["id"] == "landing_pier":
        site["note"] = "Where Gyroid wakes after the intro, at the end of the Walkway."
    sites.append(site)
for c in layout["causeways"]:
    paths.append({"from": c["from"], "to": c["to"]})

sc = layout["scenery"]
rx, ry = to_map(*layout["ringedIsle"]["pos"])
sites.append({"id": "ringed_isle", "name": "Ringed Isle (lost)", "kind": "lost", "x": rx, "y": ry,
              "note": "The island Null collapsed in the intro — open water now, ringed by dead beacons. It returns in the ending."})
tx, ty = to_map(*sc["tidewarp_flats"]["pos"])
sites.append({"id": "tidewarp_flats", "name": "Tidewarp Flats", "kind": "level", "level_id": "0-2", "x": tx, "y": ty})
mx, my = to_map(*sc["mirror_shoals"]["pos"])
sites.append({"id": "mirror_shoals", "name": "Mirror Shoals", "kind": "level", "level_id": "0-3", "x": mx, "y": my})
for f in sc["skeleton_foundry"]["sites"]:
    fx, fy = to_map(*f["pos"])
    sites.append({"id": f["id"], "name": f["name"], "kind": "bonus" if f.get("bonus") else "level", "level_id": f["level_id"], "x": fx, "y": fy})
hx, hy = to_map(*sc["hollow_throne"]["pos"])
sites.append({"id": "hollow_throne", "name": "The Hollow Throne", "kind": "castle", "castle_id": "castle-0", "x": hx, "y": hy})

g = layout["gate"]
paths += [
    {"from": "nulls_mirage", "to": "tidewarp_flats", "gate": {"needs": g["needs"], "from_level": "0-1", "note": g["note"]}},
    {"from": "tidewarp_flats", "to": "mirror_shoals"},
    {"from": "mirror_shoals", "to": "assembly_hall", "gate": {"needs": "0-3", "from_level": "0-3", "note": "Mirror Gate: opens when Gyroid shows two reefs are the same shape (homotopy equivalent)."}},
    {"from": "assembly_hall", "to": "cone_zone"},
    {"from": "cone_zone", "to": "timber_yard"},
    {"from": "assembly_hall", "to": "cylinder_works", "bonus": True},
    {"from": "timber_yard", "to": "hollow_throne", "gate": {"needs": sc["throne_bridge"]["needs"], "from_level": "0-4", "note": sc["throne_bridge"]["note"]}},
]

reef_pts = [to_map(*p) for p in [[-30.5, -9.5], [-24, 6.5], [-16, 12.5], [9.6, 12.5], [20.5, 3.5], [20.5, -6], [11, -18.8], [-1, -17.6], [-8.5, -16.8], [-30.5, -11]]]
foundry_pts = [to_map(*p) for p in [[12.5, -17.5], [21, -15.2], [29.8, -17.5], [30, -29.5], [12, -29.5]]]

MAP = {
    "note": "Generated by scripts/sync_map.py from src/world/retractReef.json — edit the layout, not this. Sites are places on the map; paths are walkable routes; a path with a gate needs an earlier tool or skill.",
    "size": [100, 60],
    "regions": [
        {"id": "retract_reef", "name": "Retract Reef", "location_id": "retract_reef", "outline": reef_pts},
        {"id": "skeleton_foundry", "name": "Skeleton Foundry", "location_id": "skeleton_foundry", "outline": foundry_pts},
    ],
    "sites": sites,
    "paths": paths,
}

for rel in ["game_concept.json", "public/data/game_concept.json"]:
    p = ROOT / rel
    c = json.loads(p.read_text(encoding="utf-8"))
    c["worlds"][0]["map"] = MAP
    p.write_text(json.dumps(c, ensure_ascii=False, indent=2), encoding="utf-8")
    print("map synced ->", rel, f"({len(sites)} sites, {len(paths)} paths)")
